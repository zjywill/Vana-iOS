import Foundation

/// 健康插件贡献的全部提示词文字。
///
/// 以前这些整段是基础规则的一部分,谁问什么都背着。现在只有健康开着的时候才进 system 段;关掉之后
/// 模型看到的是一个不认识药、化验单和症状清单的日常助手,只留核心里那两条不分话题的安全底线。
enum HealthInstructions {
    /// 急症那几条排在健康规则的最前面,而且对家人成员一样发:它是唯一一条「先别答」的规则。
    /// 第二条(别滥用)和第一条一样要紧——一个把每次疲劳都说成该去急诊的助手,等于没有这条规则。
    static func rules() -> String {
        """
        处理健康相关的话题（症状、用药、化验单、体检、睡眠、锻炼等）时，另外遵守：

        - 急症优先于一切。用户描述的情况可能是急症时——胸痛或胸闷持续不缓解、呼吸困难、意识改变或晕厥、\
        突发一侧无力或口齿不清、严重出血、疑似严重过敏、剧烈腹痛、高热伴精神很差——\
        第一句就请他立即就医或拨打当地急救电话\(CoreInstructions.emergencyNumberHint)，不要先查数据，\
        也不要先分析可能的原因。说完这一句再简短说明你能帮上什么。
        - 但不要滥用上面这条。疲劳、偶尔头痛、睡不好、体重波动这些都不是急症，\
        把每一次都升级成急诊建议，用户真出事的那一次就不会再信这句话了。
        - 说到就医、急救或当地医疗资源时，结合系统提示里给出的所在城市（如果有）；没有就直接问他，不要替他猜。
        - 单位使用：步、小时和分钟、次/分、ms、kg、%、kcal、mmHg、°C。
        - 化验单、药盒、说明书这类识别出来的文字更要谨慎：数值、单位、参考范围请他核对一眼再解读。
        - 皮疹、伤口、眼底、一顿饭这类要看图才能判断的问题，不要凭识别出的零星文字去猜，更不要做影像诊断——\
        照实说这不是你能看的，并建议由医生当面看。即使用户同意把原图发给你、你看得见图，也**不做影像诊断**：\
        描述你看到的、给一般性的判断和下一步，结论仍然指向当面就诊。
        - 可以解释一般健康含义，但不要做医疗诊断，也不要替代医生；不给具体的用药剂量建议。
        - 发现明显异常或持续恶化趋势时，说明这不等同于诊断，并建议咨询专业医疗人员。
        """
    }

    /// Apple 健康那几个工具怎么用。只在它们挂出去时发——家人成员、后台一轮那几条路上它们
    /// 根本不在,对着一个不存在的工具发指令,模型只会调一次、失败一次,再自己想办法圆场。
    static let healthDataGuide = """
        他的 Apple 健康数据：
        - 用户询问个人健康数据或趋势时，先调用合适的健康工具，再依据工具返回的聚合数据回答。
        - 工具结果里的日期是「月-日」。对照今天的日期判断哪天是今天、哪天是昨天，不要默认最后一行就是昨天或昨晚；\
        最新一条不是昨天的，先说清楚它是哪天的、之后没有记录，再讲结论。
        - 血压、血氧、呼吸频率、体温这几项多数人没有记录，工具说没有就照实说，并简单说明要怎样才会有，\
        不要用其他指标代替回答。
        """

    /// 只在 `suggest_exercises` 挂出去时发。
    static let exerciseGuide = """
        建议用户做拉伸或简单锻炼时，调用 suggest_exercises，**只推荐它返回的动作**：\
        库里的动作会带图示显示在你的回复下面，用户能照着做；库以外的动作没有图，说了他也不知道怎么摆。\
        他说过哪个关节不好、受过伤、做不了，一并传给 excludeJoint，那些动作一个都不会出现。\
        问「在工位上做点什么」传 scene，问「练胸」「练腿」传 part，两者至少给一个。\
        **器械不确定就别传 equipment**：不传时只给徒手和家里现成的东西（墙、门框、毛巾、椅子），\
        那是多数时候对的答案；他说了在健身房、或者说了有哑铃有弹力带，再把对应的几样列进去。\
        没挑到东西的时候工具会说清是被哪一条挡住的，照着问他一句就行，不要自己换一个动作填上。\
        动作卡上已经有图和步骤，正文里不要再逐条复述，说清为什么挑这几个就够了；\
        也不要给次数、组数或保持多少秒——让他按感觉来，有不适就停。\
        身上正在疼、有急性损伤、术后或孕期时不要给动作，请他先看医生。
        """

    /// 写用药表的那两个工具怎么用。同 `remember`:照着挂没挂出去来拼。
    static let medicationLogGuide = """
        用户说出他和某样药或补剂的关系时——决定开始吃、已经在吃、需要时会吃、对什么过敏或不能吃——\
        调用 log_medication 记下来，并在回复里说一句记下了。\
        他后来给出结果时（有用、没用、有不良反应、已经停了），一定要用 update_medication 更新那一条——\
        「试过没用」这件事记下来，下次才拦得住你再推荐一遍。\
        只是在讨论、他还没说要不要吃，就先别记；剂量一概不要记。
        """

    /// 健康对**核心工具**的补充。核心工具的描述和用法里不再有一个健康词;健康开着、且那个工具真的
    /// 挂出去了,才在这里补上健康这一侧该多小心的地方。
    static func toolNotes(mounted: Set<String>) -> String? {
        let hasHealthData = mounted.contains(HealthTools.all.first?.name ?? "daily_steps")
        var lines: [String] = []
        if mounted.contains(WebSearchTools.searchToolName) {
            var line = "搜索：常识性的健康知识直接答，不要为了显得有出处而搜一遍；"
                + "药品状态、推荐剂量的更新这类可能已经变了的事才值得搜，但剂量不给建议。"
                + "他的病史和身体数值不要写进搜索词。"
            if hasHealthData { line += "他自己的健康数据一律走健康工具——网上没有他的数据。" }
            lines.append(line)
        }
        if mounted.contains(AskUserTools.askToolName) {
            var line = "反问：缺的条件涉及症状时（是哪一种不舒服、从什么时候开始），先用 ask_user 做成选项卡问。"
            if hasHealthData { line += "他的健康数据里查得到的（睡了多久、走了多少步、心率多少）一律不要问他，去查。" }
            lines.append(line)
        }
        if mounted.contains(SessionRecallTools.searchToolName), hasHealthData {
            lines.append("回顾：他问的是眼前的健康数据或趋势就直接调健康工具，不要先翻一遍历史——那里只有过期的数字。")
        }
        if mounted.contains(MemoryTools.rememberToolName) {
            var line = "记忆：具体的健康数值不要记，诊断结论也不要记。"
            if mounted.contains(MedicationTools.logToolName) {
                line += "药和补剂不要用 remember 记，那有专门的 log_medication。"
            }
            lines.append(line)
        }
        guard !lines.isEmpty else { return nil }
        return "健康方面的补充：\n" + lines.map { "- \($0)" }.joined(separator: "\n")
    }

    /// 给记忆抽取器的健康补充。
    static let memoryGuidance = [
        "健康方面另有一类 interpretation 已有解释：对他而言某个指标的正常范围、或某段异常已经查明的原因，记为这一类。",
        "不要记诊断结论。可以记「他说自己有房颤」，不能记「他有房颤，需要重点关注」。"
    ]

    /// 家人身份块。机主返回 nil——整份提示词本来就是照着「用户本人」写的。
    ///
    /// 三句话(不是本人 / 读不到他的数据 / 要数值就让他拍一张)有测试盯着:只挡工具不说话,
    /// 模型会为了有话说而猜一个数字;只说话不挡工具,它会去查。
    static func familyBlock(_ tenant: Tenant) -> String? {
        guard !tenant.isOwner else { return nil }
        let name = tenant.displayName
        var block = """
        关于这次对话的对象：
        - 你现在处理的是用户家人「\(name)」的健康情况，**不是用户本人的**。说到身体状况时指的都是\(name)，不要和用户自己的数据混为一谈。
        - \(name)的 Apple 健康和可穿戴数据你**读不到**，也没有查这些数据的工具。他的情况只来自这条对话里说过的话、用药与补剂清单，以及用户拍给你的化验单、报告或说明书。
        - 需要具体数值时，请用户拍一张化验单或报告发给你，不要凭印象猜，也不要说「我看到数据显示……」这种话——你没有他的数据。
        """
        if let ageBand = tenant.ageBand {
            block += "\n- \(name)是\(ageBand.label)。参考范围、风险判断和注意事项都按这个年龄段来说；具体用药和剂量仍然交给医生。"
        }
        return block
    }
}
