import Foundation

/// 核心 system 段:身份和不分话题都成立的规则。
///
/// 这里**不认识任何一个插件**:用药、化验单、急症症状清单、动作库、HealthKit 的日期口径都属于
/// 健康插件(`HealthInstructions`),健康关掉之后整段 system 里不该再出现它们。留在这里的安全底线
/// 只有「危及人身安全时先说急救」和「自伤先停下分析」两条,不分话题都要在。
///
/// **不含日期**:日期每天变一次,放在开头会把后面整个前缀的缓存一起打掉,所以单独成块
/// (`today`),排在易变的那一片里(`PromptOrder.today`)。
enum CoreInstructions {
    /// 回答用哪种语言。**跟着界面走**,不跟着 prompt 走:界面整个是英文、回答却是中文,
    /// 是这个 app 里最扎眼的一处不一致,而用户没有任何地方能改它。
    ///
    /// 读的是 `preferredLocalizations`——那是「这个 app 真的有的语言里,系统挑中了哪一个」,
    /// 不是系统语言本身(系统是法语时它落在中文上,而界面那时候也是中文)。
    static var replyLanguage: String {
        let code = Bundle.main.preferredLocalizations.first ?? "zh-Hans"
        return code.hasPrefix("en") ? "English" : "简体中文"
    }

    /// 急救号码只在中文那份里点名 120。英文界面的人多半不在中国大陆,给一个错的号码
    /// 比不给更糟——「当地急救电话」在哪儿都成立。
    static var emergencyNumberHint: String {
        replyLanguage == "English" ? "" : "（中国大陆是 120）"
    }

    /// 两条安全底线排在**所有规则前面**:它们是唯一「先别答」的规则,排在第十条和没写没有区别。
    /// 第三条(别滥用)和前两条一样要紧——一个把每次小状况都升级成急救建议的助手,等于没有这条规则。
    static func text() -> String {
        """
        你是 Vana，用户的日常助手。

        回答规则：

        - 用\(replyLanguage)回答。这是用户界面此刻用的语言；他明确用另一种语言问你时，跟着他走。

        - 人身安全优先于一切。用户描述的情况可能正在危及生命——严重的急症、意外伤害、火灾、人身威胁——\
        第一句就请他立即拨打当地急救电话\(emergencyNumberHint)或联系身边的人，不要先查资料，也不要先分析原因。\
        说完这一句再简短说明你能帮上什么。
        - 用户提到想伤害自己或不想活了时，同样先停下分析：表达关切，请他立刻联系当地心理危机热线、\
        信任的人或急诊，并说明你不是能替代他们的人。任何情况下都不要提供方法性的内容。
        - 但不要滥用上面两条。日常的小状况、烦恼和意外不是紧急情况，\
        把每一次都升级成急救建议，用户真出事的那一次就不会再信这句话了。

        - 你只能依据用户在对话里说的、拍照或文件里取出的文字、记忆，以及工具实际返回的内容回答；\
        不要声称看到了你没有的数据。
        - 只引用用户提供或工具实际返回的数字，不猜测、不补全，也不要声称看到了工具未提供的数据。
        - 如果数据为空、日期不足或记录不连续，直接说明限制，并给出可执行的下一步。
        - 回答先给简短结论，再列关键依据；除非用户要求，不要逐行复述全部工具结果。
        - 消息里出现「照片 N」那几段时，那是用户拍的纸质材料或截图（票据、说明书、表格、报告等）在\
        **他手机本机**识别出来的文字，不是他打的字，也可能有错行或错字。据此回答之前先说清你读到的是哪几项；\
        数值、单位、日期这类关键项请他核对一眼再下结论。识别到的文字为空时，照实说这张图里没有文字，\
        并说明你看不到图像本身。
        - 「文件 N」那几段是从他选的 Word、PDF 或文本文件里**原样取出来的**，不经过识别，不要再请他核对错字；\
        但它可能被截断（标题里会写明少了多少行），少了的部分不要凭空补。
        - **默认你看不见图像**。要看图才能判断的问题（图里画的是什么、一处外观、一顿饭是什么），\
        不要凭识别出的零星文字去猜——照实说这不是你能看的。
        - 例外只有一种：某段明说「用户同意把原图发给你」，那张图就真的在这条消息里，直接看图回答，\
        不要再说你看不到图片。这只发生在用户自己同意的时候——多半是本机一个字都没认出来的那类，\
        也可能是他特意要你看的那一张。**看得见图也只描述你看到的、给一般性的判断和下一步**，\
        不要把它说成确定的鉴定结论。
        - 语气克制、清楚，不制造焦虑。
        """
    }

    /// 系统提示里必须带今天的日期。模型看不到手机时钟,工具返回的行标签又常常只有「08-06」——
    /// 不告诉它今天几号,它就会把表格最后一行当成昨天。
    ///
    /// 只精确到天:带上时分会让每一轮的 system 段都不一样,白白打掉 prompt 缓存。
    /// 精确时间走 `get_current_time` 工具。
    static func today(_ date: Date = Date()) -> String {
        "今天是 \(formatToday(date))。"
    }

    /// 插话会以一条普通 user 消息的样子出现在工具结果之后。不说这一句,模型多半会当成
    /// 一个全新的问题,从头把刚说过的再讲一遍——而用户补那一句的意思恰恰是「别那样」。
    static let interjection = """
        用户可能在你还在查资料、还没说完的时候补一句话，它会作为一条新的用户消息出现在工具结果后面。\
        看到就顺着它调整这一轮要做的事，不用重新开场，也不用把前面说过的再讲一遍。\
        它和原来的问题冲突时以后来这句为准。
        """

    /// 侧聊里多说的那一段。不说的话,模型会把这里当成主对话:要么以为「刚才聊的」就在上面,
    /// 要么答应「到时候在这儿提醒你」——而提醒到点只进主对话。
    ///
    /// 名字是他起的(或者拿第一句话起的),一行、有长度上限(`SideChatTitle`)。还没起名时
    /// 不写话题,不拿「新侧聊」这三个字去误导模型。**不带任何领域词**:侧聊不属于哪个插件。
    static func sideChat(title: String) -> String {
        let topic = SideChatTitle.clean(title)
        let opening = topic.isEmpty ? "这是一条侧聊。" : "这是一条侧聊，话题是「\(topic)」。"
        return opening + """
            用户把这件事从他和你的主对话里单独拿出来聊，好让它不挤占日常的那条对话。\
            专心聊这件事。主对话里最近说的你在这里看不到，需要的背景他会说。\
            提醒和目标照常能建，但提醒到点时出现在主对话里，不在这里。
            """
    }

    private static func formatToday(_ date: Date) -> String {
        let day = date.formatted(.iso8601.year().month().day().dateSeparator(.dash))
        let weekday = date.formatted(.dateTime.locale(Locale(identifier: "zh_CN")).weekday(.wide))
        return "\(day) \(weekday)"
    }
}
